import { mkdirSync, writeFileSync, existsSync, readFileSync, readdirSync } from 'node:fs'
import { resolve } from 'node:path'

// ─── Generate seeder template ──────────────────────────────────────────────────

export function generateSeeder(
    seedersFolder: string,
    name: string,
): string {
    if (!existsSync(seedersFolder)) {
        mkdirSync(seedersFolder, { recursive: true })
    }

    const fileName = `${name}.seeder.ts`
    const filePath = resolve(seedersFolder, fileName)
    const content = generateSeederContent(name)

    writeFileSync(filePath, content, 'utf-8')
    console.log(`  ✔ Generated seeder: ${fileName}`)

    return filePath
}

